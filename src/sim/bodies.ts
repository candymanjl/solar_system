export type BodyKind = "star" | "planet" | "dwarf" | "moon" | "asteroid" | "comet" | "lagrange";

export type BodyLayer = "core" | "asteroid" | "kuiper" | "comet" | "lagrange";

export type TextureKind =
  | "sun"
  | "mercury"
  | "venus"
  | "earth"
  | "moon"
  | "mars"
  | "jupiter"
  | "saturn"
  | "uranus"
  | "neptune"
  | "pluto"
  | "io"
  | "europa"
  | "ganymede"
  | "callisto"
  | "titan"
  | "triton"
  | "icy"
  | "rocky"
  | "phobos";

export type EphemerisKind =
  | { type: "star" }
  | { type: "planet"; body: "Sun" | "Mercury" | "Venus" | "Earth" | "Mars" | "Jupiter" | "Saturn" | "Uranus" | "Neptune" | "Pluto" | "Moon" }
  | { type: "jupiterMoon"; moon: "io" | "europa" | "ganymede" | "callisto" }
  | {
      type: "kepler";
      parentId: string;
      aKm: number;
      e: number;
      iDeg: number;
      periodDays: number;
      argPeriDeg: number;
      meanAnomalyDeg: number;
      lanDeg: number;
      epochJd: number;
    }
  | { type: "lagrange"; pair: "sel" | "eml"; point: 1 | 2 | 3 | 4 | 5 };

export type BodyDef = {
  id: string;
  name: string;
  kind: BodyKind;
  parentId: string | null;
  radiusKm: number;
  flatten: number;
  color: string;
  orbitColor: string;
  atmosphere?: string;
  rings?: { inner: number; outer: number };
  texture: TextureKind;
  ephemeris: EphemerisKind;
  periodDays: number;
  rotationHours: number;
  gmKm3s2?: number;
  layer?: BodyLayer;
  blurb: string;
};

const J2000_JD = 2451545.0;

export const AU_KM = KM_PER_AU;

function helioKepler(
  aAu: number,
  e: number,
  iDeg: number,
  lanDeg: number,
  argPeriDeg: number,
  meanAnomalyDeg: number,
  periodDays: number,
  epochJd = J2000_JD,
): EphemerisKind {
  return {
    type: "kepler",
    parentId: "sun",
    aKm: aAu * AU_KM,
    e,
    iDeg,
    periodDays,
    argPeriDeg,
    meanAnomalyDeg,
    lanDeg,
    epochJd,
  };
}

export function kmToAu(km: number) {
  return km / AU_KM;
}

export function auToKm(au: number) {
  return au * AU_KM;
}

