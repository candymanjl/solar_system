export const BODY_BY_ID: Record<string, BodyDef> = Object.fromEntries(BODIES.map((b) => [b.id, b]));

export const PLANETS = BODIES.filter((b) => b.kind === "planet" || b.kind === "dwarf");
export const MOONS = BODIES.filter((b) => b.kind === "moon");

export function childrenOf(id: string) {
  return BODIES.filter((b) => b.parentId === id);
}

export function radiusAu(body: BodyDef) {
  return kmToAu(body.radiusKm);
}

export function moonSystemRadiusAu(parentId: string) {
  let max = 0;
  for (const m of BODIES) {
    if (m.parentId !== parentId) continue;
    if (m.ephemeris.type === "kepler") {
      max = Math.max(max, kmToAu(m.ephemeris.aKm * (1 + m.ephemeris.e)));
    } else if (m.id === "moon") {
      max = Math.max(max, kmToAu(405400));
    } else if (m.ephemeris.type === "jupiterMoon") {
      const a: Record<string, number> = {
        io: 421800,
        europa: 671100,
        ganymede: 1070400,
        callisto: 1882700,
      };
      max = Math.max(max, kmToAu(a[m.ephemeris.moon] ?? 0));
    }
  }
  return max;
}

export function framingDistanceAu(id: string) {
  const b = BODY_BY_ID[id];
  if (!b) return 12;
  if (b.kind === "star") return 18;
  if (b.kind === "lagrange") return b.id.startsWith("eml") ? 0.00045 : 0.028;
  if (b.kind === "comet") return Math.max(radiusAu(b) * 80, 0.06);
  const moons = moonSystemRadiusAu(id);
  const r = radiusAu(b);
  if (moons > 0) return Math.max(moons * 3.4, r * 28, 0.0008);
  if (b.kind === "moon") return Math.max(r * 22, 0.00008);
  if (b.kind === "asteroid" || b.kind === "dwarf") return Math.max(r * 36, 0.002);
  return Math.max(r * 40, 0.004);
}
